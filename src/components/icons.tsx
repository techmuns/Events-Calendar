import type { CSSProperties, ReactNode } from "react";

function Svg({
  size = 16,
  children,
  style,
  fill = "none",
  strokeWidth = 2,
}: {
  size?: number;
  children: ReactNode;
  style?: CSSProperties;
  fill?: string;
  strokeWidth?: number;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={fill}
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      style={{ display: "block", ...style }}
      aria-hidden
    >
      {children}
    </svg>
  );
}

